// Bake the actual WebGL rest state: identical mesh, material, light and camera.
// Run with the local server at MOBIUS_BASE_URL (default port 4173).
const fs=require('node:fs');
const path=require('node:path');
const {chromium}=require(process.env.PLAYWRIGHT_PATH||'C:/Users/SBS/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
(async()=>{
  const browser=await chromium.launch({headless:true,executablePath:process.env.CHROME_PATH||'C:/Program Files/Google/Chrome/Application/chrome.exe',args:['--enable-webgl','--use-angle=swiftshader','--enable-unsafe-swiftshader']});
  try{
    const page=await browser.newPage({viewport:{width:1320,height:800},deviceScaleFactor:1});
    const base=process.env.MOBIUS_BASE_URL||'http://127.0.0.1:4173';
    await page.route('**/mobius-poster',route=>route.fulfill({contentType:'text/html',body:'<!doctype html><html><body style="margin:0"><div id="poster" style="width:1320px;height:800px"><canvas></canvas></div></body></html>'}));
    await page.goto(base+'/mobius-poster');
    const png=await page.evaluate(async()=>{
      const {initMobius}=await import('/mobius.js');
      // Read immediately after drawing, before the drawing buffer is cleared.
      const proto=WebGLRenderingContext.prototype,draw=proto.drawElements,uniform=proto.uniform1f,locate=proto.getUniformLocation;
      const names=new Map();let textureReady=false;
      const ready=new Promise(resolve=>{
        proto.getUniformLocation=function(p,n){const l=locate.call(this,p,n);names.set(l,n);return l;};
        proto.uniform1f=function(l,v){if(names.get(l)==='uHasEnvironment'&&v===1)textureReady=true;return uniform.call(this,l,v);};
        proto.drawElements=function(...args){draw.apply(this,args);if(textureReady)resolve(this.canvas.toDataURL('image/png'));};
      });
      const host=document.querySelector('#poster');
      initMobius({host,section:host,reduced:matchMedia('(min-width:0px)')});
      return await ready;
    });
    if(!png.startsWith('data:image/png;base64,')||png.length<10000)throw Error('Poster capture failed');
    fs.writeFileSync(path.join(__dirname,'dist/assets/tools-mobius.svg'),`<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1980 1200"><!-- Rest-state render from mobius.js and blue-chrome.jpg; generated by render-mobius-poster.cjs. --><image width="1980" height="1200" href="${png}"/></svg>\n`);
    console.log('Built tools-mobius.svg from the live material');
  }finally{await browser.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
